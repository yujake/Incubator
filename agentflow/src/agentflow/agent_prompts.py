def _apply_no_lean_variant(text: str) -> str:
    """开关关掉时，按 `specs/<role>.py` 的那三张表改写渲染出来的提示词。

    业主 2026-10-12（逐字）：「负责 Lean 的智能体 E 在开关关掉时可不载入有关形式化验证的
    提示词，全体成员关于 E 的印象也可以没有『负责形式化验证』这个说法，一旦提到形式化验证
    所有人的第一反应是系统做不了」。2026-10-22 新设 L 之后，这条口径同时管两个角色
    （B / E 各有一份表，见 `_no_lean_tables`）；L 自己那一份在 2026-10-25 退役（它不可达：
    关着时 L 不存在，收口读不到它的一句话）。

    四处刻意的做法：

    - 改写表住在 `specs/b.py` / `specs/e.py`（各自声明旁边）：声明本身一个字不改
      （它派生权限面的四张表、被冻结快照钉着），随开关变的只是"渲染给模型看的那份文本"；
    - 应用点是唯一的收口（`system_prompt` / `prompt_audit` 都经过它）—— 提示词有多条
      渲染路径（角色段 / 伙伴表 / 工具面 / 政策），逐条去改会漏掉某一条，
      而漏掉的表现正是"某个角色还以为 E 负责形式化验证"；
    - 顺序固定：先整块删（跨行的"整块都在讲形式化"），再整行删，最后逐条替换。
      删掉的内容里可能含有后面两步要匹配的片段，反过来做会留下半句话；
    - 开关开着时逐字返回原文（连一次字符串替换都不做）—— 开着时的行为与加这张表之前
      逐字一致，这一条由 `tests/test_lean_switch.py` 的负控守着。
    """
    if _lean_switch()[0]:
        return text
    for _name, blocks, drop, replacements in _no_lean_tables():
        # 顺序一字未变：先整块删、再整行删、最后逐条替换（三张表各自独立）。
        # 整块删与整行删共用一次 split / 一次 join（改前每删一块都整文 split 一遍、
        # join 一遍；M 岗的正文 73 KB，而三张表里有两张根本没有块也没有行标记）。
        if blocks or drop:
            lines = text.split("\n")
            for start, keep in blocks:
                kept: list[str] = []
                skipping = False
                for line in lines:
                    if not skipping and start in line:
                        skipping = True
                    if skipping and keep and keep in line:
                        skipping = False
                    if not skipping:
                        kept.append(line)
                lines = kept
            if drop:
                lines = [line for line in lines if not any(mark in line for mark in drop)]
            text = "\n".join(lines)
        for old, new in replacements:
            text = text.replace(old, new)
    return text
def system_prompt(role: str, **kw: Any) -> str:
    """渲染某个角色这一次的 system prompt。"""
    return _apply_no_lean_variant(role_prompt_registry(role, **kw).render(Scope(role=role)))
def prompt_audit(role: str, **kw: Any) -> dict[str, Any]:
    """这次提示词的审计读数：版本、哈希、长度、段名、变量名。

    每次模型调用都要把这份读数落档 —— 没有它，
    "这次结论是哪个版本的提示词加上哪个模型的产物"就无法事后回答。

    2026-11-22（PRESETRETIRE）：这里此前还有一格 `preset`（"这一趟读的是哪一份
    预设组装文件、它有没有坏到让内置那份顶上来"）。预设机制退役之后那一格没有
    对象 —— 留一个恒为空壳的键，会让读数看起来还在回答一个已经不存在的问题。
    """
    reg = role_prompt_registry(role, **kw)
    assembly = reg.assemble(Scope(role=role))
    text = _apply_no_lean_variant(assembly.render())
    return {
        "prompt_version": PROMPT_VERSION,
        "role": role,
        "prompt_sha256": hashlib.sha256(text.encode("utf-8")).hexdigest(),
        "prompt_chars": len(text),
        "sections": list(assembly.names),
        "variables": sorted(assembly.variables),
    }
def user_replies_digest(replies: Sequence[Mapping[str, Any]], limit: int = 6) -> str:
    """把用户的回答渲染成提示词里的一段（含"这条是迟到的"标记）。







    迟到的回答与及时的一样重要：模型必须知道用户说过什么，



    哪怕那句话是在它上一次提问超时之后才到的。



    """
    if not replies:
        return ""
    lines: list[str] = []
    for r in replies[-limit:]:
        mark = "（迟到送达）" if r.get("late") else ""
        lines.append(f"- [{r.get('qid')}]{mark} 问：{_clip_text(r.get('question'), 120)} "
                     f"→ 用户答（{r.get('by')}）：{_clip_text(r.get('answer'), 300)}")
    return "\n".join(lines)
