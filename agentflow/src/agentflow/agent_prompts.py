#: 只对"出边为空"的角色处理的那一块（[c] 连同它后面那个空行）。
#:
#: 对这一档不整块删，换一行残桩（`_LOOP_EDGELESS_STUB`）：表头那句
#: 「十一种形状，互斥，每次只取其一：」不在任何一块里（它是常量自己的正文），
#: 而它是真的（`agent_loop.SHAPES` 是 11 个，`JSON_TAIL` 每一步也把含 `summon_many`
#: 的骨架发给所有角色）。把 [c] 整块删掉之后，这一档会读到"八种"却只数得出 7 项 ——
#: 描述与自身矛盾。留一行残桩 ⇒ 表头仍然为真、列表仍然枚举 8 项，
#: 而它不再读到那 565 字"什么时候用、怎么填"的用法说明。
#:
#: 为什么 [c] 带两个换行、而 [a]/[b] 只带一个：三块与上下文之间的空行分布不同 ——
#: [a] 紧接在"2)"的示例后面（它前面没有空行），[a] 与 [c] 之间一个空行、[c] 与"3)"
#: 之间一个空行。删 [a]/[b] 时只吃它们自己那一行的换行（[c] 前面那个空行留着当"2)"
#: 与"2b)"之间的分隔）；[c] 那一块连它后面那个空行一起被换掉（"2b)"与"3)"之间仍留一个
#: 空行）。结果是每一版里都没有多余或缺失的连续空行（三版实测 `\n\n\n` 计数都是 0）。
_LOOP_EDGELESS_ONLY_BLOCKS: tuple[str, ...] = (
    _LOOP_BLOCK_C + "\n\n",
)

#: 出边为空的角色那一版里的 `2b)`（残桩：一行，说明这一档用不到 + 骨架在哪看）。
_LOOP_EDGELESS_STUB = ("2b) 一次唤起一批（这一档你用不到：你没有任何协作边，派不出活 —— "
                       "骨架见每步的 JSON 尾巴）。")

assert all(LOOP_PROTOCOL.count(_blk) == 1
           for _blk in _LOOP_CONDUCTOR_ONLY_BLOCKS + _LOOP_EDGELESS_ONLY_BLOCKS), (
    "循环协议里那几块与 `LOOP_PROTOCOL` 对不上了：块被改过、被搬过、或在常量里出现了"
    "不止一次。漂了必须当场炸 —— 否则某一版会静默地少删半块，而主控那一版照样"
    "逐字节不变、没有任何读数会红。先按行号重新取一次那几块。")


def loop_protocol_for(role: str) -> str:
    """循环协议按角色渲染（`R6` §2-⑥ 的结构性搬移）。两组作用域不一样，别混。

    `M`：今天的常量本身 —— 直接返回 `LOOP_PROTOCOL`，一个字节都没有重新拼装。

    其余角色：
      - 任何非 M：[a] 主控留痕块 / [b] 主控例外句删掉（它们说的是"主控派活怎么留痕"
        与"主控的 final 不必带 notify"，对别的角色是死文本）；
      - 再加上：出边为空的角色把 [c] 2b 整段换成一行残桩（`_LOOP_EDGELESS_STUB`）
        —— 它教的是"一次唤起一批"，而一个伙伴都唤不动的角色写得出这个形状却没有目标
        可填。残桩不删表头那一项：那句"十一种形状"是真的（`agent_loop.SHAPES` 是 11 个），
        整块删掉会让这一档读到"八种"却只数得出 7 项。
        判据是现算的 `capabilities.ALLOWED_EDGES[role]`（不写死角色名、也不看是不是主控）。

    判据在 `tests/test_agent_prompts.py`：三组各自的出现集合逐角色钉死（[c] 整段必须
    恰好只在"出边非空"的角色里、残桩必须恰好只在"出边为空"的角色里），且每一版都要
    逐字节等于"用判据自己那份逐字副本算出来"的结果 —— 少删半块、多删一段、换行口径
    不同、或者把残桩也删了，都会红。
    """
    if str(role) == S.CONDUCTOR_ROLE:
        return LOOP_PROTOCOL
    out = LOOP_PROTOCOL
    for block in _LOOP_CONDUCTOR_ONLY_BLOCKS:
        out = out.replace(block, "", 1)
    if not C.ALLOWED_EDGES.get(str(role), ()):
        # 一个伙伴都唤不动（今天只有 C）：2b 那一段对它无从填起，换一行残桩。
        old, new = _LOOP_EDGELESS_ONLY_BLOCKS[0], _LOOP_EDGELESS_STUB + "\n\n"
        out = out.replace(old, new, 1)
    return out


