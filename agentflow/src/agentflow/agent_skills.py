#: 为什么要有这个正则而不是"看见像工具就报"：正文里还会出现 `D.propose_question`
#: （动作，角色名大写）、`data/statements.json`（路径）、`main.tex`（文件名）——
#: 它们都不是工具。**只报"确实在工具面上存在、但不属于这个角色"的那一种**，
#: 这样零假阳性，而真缺陷（"V 用 `fs.write` 落盘"这种做不到的指令）一个不漏。
_BODY_TOOL_TOKEN = re.compile(r"`([a-z][a-z0-9_]*\.[a-z0-9_]+)`")


def _body_tool_problems(surface: dict[str, set[str]]) -> list[str]:
    """**正文里**点名的工具也必须在这个角色自己的工具面上。

    ## 为什么 `tools` 那一格不够

    `tools` 是声明，正文是**操作手册**。一条 skill 完全可以把 `tools=("fs.read",)`
    写得干干净净，却在正文第一句写"用 `fs.write` 把结果落盘" —— 而 `fs.write`
    正是只读角色拿不到的那一件。声明那一格查得再严也管不到这句话，
    而模型照做的对象是**正文**。

    ## `shared` 那一槽为什么豁免（这是明写出来的豁免，不是漏查）

    `shared` 是**每个角色都读得到**的同一份文件。它此前声明用 `table.*`，
    而 M 的工具面里没有库表类工具 ⇒ 那两句对 M 是做不到的指令。改法不是"把它删干净"，
    而是**在正文里点明这一格与角色有关**（"库表工具在多数角色手上、主控用 `fs.read`
    读同一份 JSON"）—— 那句话里必然同时出现 `table.get` 与 `fs.read`，
    所以对共享那一份，按"每个角色都必须在面上"判会把它自己判死。
    共享那一份的纪律因此是**声明**那一格（`tools`）取交集，判据在 `validate()` 的工具循环里。
    """
    known: set[str] = set()
    for names in surface.values():
        known |= names
    if not known:
        return []          # 工具面没读成 ⇒ 这一格跳过（validate 已经记过"没查成"）
    out: list[str] = []
    for owner, rows in CATALOG.items():
        if owner == SHARED:
            continue
        allowed = surface.get(owner, set())
        for s in rows:
            for tok in sorted(set(_BODY_TOOL_TOKEN.findall(s.body))):
                if tok in known and tok not in allowed:
                    out.append(
                        f"{owner}/{s.slug}：正文里点名了工具 {tok}，但它不在 {owner} 的工具面上"
                        "（声明那一格查不出这种写法，而模型照做的是正文）")
    return out


#: 正文里那种"点名一个动作"的写法：反引号包着的 `大写角色.动作`。
#:
#: 形状与工具名**天然分得开**（工具是全小写的 `组.名`），所以这个正则零假阳性：
#: `data/statements.json`（路径）、`main.tex`（文件名）、`re.compile`（标准库）
#: 都不会命中。零假阳性是这条判据能活下来的前提。
_BODY_ACTION_TOKEN = re.compile(r"`([A-Z])\.([a-z][a-z0-9_]*)`")

#: 正文里**指到别人**的那种 `角色.动作`（不是让本角色去做）：逐条登记 + 一行理由。
#:
#: ## 口径
#:
#: 正文里的 `角色.动作` 默认必须从**拥有这条 skill 的角色**出发够得到（与 `actions`
#: 那一格同一条纪律）。登记在这里的是例外 —— 它们出现在**"这不是我的活"**的句子里，
#: 指到别人或别人产出的证据。**逐条登记而不是放宽判据**：多出一处就要有人看一眼
#: "这是指到别人，还是真让人去做"。
#:
#: ## 反例比正例重要（为什么不干脆只查"动作存不存在"）
#:
#: 只查存在性会漏掉真缺陷：一条 skill 说"你自己去调 `F.step`"时，动作确实存在，
#: 而那个角色**做不到**。而如果为了抓这一句就把"指到别人"也判红，判据立刻变成噪音
#: （实测这三处都是正当的指到别人）——所以豁免必须**具名**，且必须能被反查（见下）。
_BODY_CROSS_REFS: dict[tuple[str, str, str], str] = {
    ("C", "矛盾-三态并指到那一对", "D.adjudicate"):
        "「C 只判、不改：矛盾问题的闭环由 D 的 `D.adjudicate` 收口（I2）」—— 指到别人",
    ("G", "成稿-正文自己写而不是脚本生成", "H.review"):
        "「稿件级审校由 **H** 做（`H.review`）」—— 指到别人",
    ("V", "假设轴-前提是否真被满足", "E.check_formal"):
        "「能机器核的（`E.check_formal` 过的那几条）」—— 指到别人产出的证据",
}


def _body_action_problems() -> list[str]:
    """**正文里**提到的动作：必须真存在；够不到就要**具名登记**为"指到别人"。

    `actions` 那一格是声明，正文是操作手册 —— 一句"派 `F.step` 去推"写在正文里，
    声明那一格查得再严也管不到它，而模型照做的对象是**正文**（与
    `_body_tool_problems` 同一条理由，只是这一格查的是动作而不是工具）。

    三件事各查一遍：

    1. **存在**：正文里任何一个 `角色.动作` 都必须在 `capabilities` 里（业主 ④：
       严禁虚构本系统不存在的动作）；
    2. **够得到**：从拥有这条 skill 的角色出发，要么是自己的动作、要么在它的出边里；
       够不到但确实是"指到别人"的，必须登记进 `_BODY_CROSS_REFS`；
    3. **登记不许腐烂**：登记过的每一条都必须还成立（skill 还在、正文里还有那一句、
       而且从出边看**仍然**够不到）—— 一张永不生效的豁免表会腐烂成"看起来还在挡着什么"。
    """
    try:
        from . import capabilities as C
    except Exception as exc:  # noqa: BLE001 —— 没查成也要报（不许读成"没问题"）
        return [f"读不到 capabilities（正文动作那一格没查成）：{type(exc).__name__}: {exc}"]
    out: list[str] = []
    hit: set[tuple[str, str, str]] = set()
    for owner, rows in CATALOG.items():
        for s in rows:
            reachable = set(C.ALLOWED_EDGES.get(owner, ()))
            for role, action in sorted(set(_BODY_ACTION_TOKEN.findall(s.body))):
                item = f"{role}.{action}"
                if C.find_action(role, action) is None:
                    out.append(f"{owner}/{s.slug}：正文里的 {item} 不是本系统里存在的动作")
                    continue
                if owner == SHARED or role == owner or role in reachable:
                    continue
                key = (owner, s.slug, item)
                if key in _BODY_CROSS_REFS:
                    hit.add(key)
                    continue
                out.append(
                    f"{owner}/{s.slug}：正文里的 {item} 不在 {owner} 的出边里"
                    "（写进去就是一句做不到的指令）。若这一句是「指到别人」，"
                    "请登记进 `_BODY_CROSS_REFS` 并写明理由")
    for key, why in sorted(_BODY_CROSS_REFS.items()):
        if key not in hit:
            out.append(
                f"{key[0]}/{key[1]}：`_BODY_CROSS_REFS` 里登记的 {key[2]} 已经不成立"
                f"（要么这句正文没了、要么它现在够得到了）⇒ 请删掉这条登记，"
                f"别让豁免表腐烂。理由原话：{why}")
    return out


#: 工作区里**允许**被点名的路径根（业主 2026-10-14「现做现读」那一批的落点全集）。
#:
#: 为什么要有这张表：一条 skill 说"去 `foo/report.md` 读结论"，而**没有任何东西会产出那个文件**
#: —— 读的人找不到，写的人也没错，两边都不报错。所以落点必须落在这张表里的某个根下。
#: 加新落点时**同时加这里**（这一条是那件事的机器形态；判据见 `_path_problems`）。
WORKSPACE_PATH_ROOTS: tuple[str, ...] = (
    "out/",          # 框架的产物区（论文、审校报告、任务全文、秘书台账）
    "reports/",      # 研究手稿与攻坚台账（D / F 的落点）
    "data/",         # 台账表落盘后的那份 JSON
    "code/",         # 脚本与 Lean 源码
    "skills/",       # 各角色的操作手册（本模块 materialize 写的）
    "notes/",        # 草稿本
    "manuscripts/",  # 交接手稿
    "source/",       # 审阅型工作区的只读基线
    "verifications/",  # V 的复核台账
    "sessions/",     # 会话记录
)

#: 仓库里**允许**被点名的路径根（文档与源码 —— 提示词里引用它们是正当的，但它们不是工作区）。
REPO_PATH_ROOTS: tuple[str, ...] = ("draft/", "docs/", "src/", "tests/", "scripts/", "tools/")

#: 上面两张表合起来就是"一个落点可以落在哪儿"。
PATH_ROOTS: tuple[str, ...] = WORKSPACE_PATH_ROOTS + REPO_PATH_ROOTS

#: 反引号里那种"带目录的路径"：`a/b`、`a/b/c.md`、`a/b/`（目录形态）。
_PATHY = re.compile(r"`([A-Za-z0-9_.\-]+(?:/[A-Za-z0-9_.<>*\-]+)+/?)`")

#: 认得出的**文件后缀**：只有"带目录**且**像文件/目录"的串才判（见 `_path_problems` 的口径）。
_PATH_SUFFIXES: tuple[str, ...] = (".md", ".json", ".jsonl", ".tex", ".pdf", ".py",
                                   ".lean", ".csv", ".bib", ".txt", ".yaml", ".yml")


def _looks_like_a_path(tok: str) -> bool:
    """这个反引号串是"一个落点"吗（而不是别的东西碰巧带斜杠）。

    ## 为什么必须加这一道筛子（现算读数）

    第一版只按"带目录"判，于是 `heuristic/inconclusive` 当场被报成"没人写的落点" ——
    而它是**证据等级的词表取值**（`heuristic` / `inconclusive` 那一档），
    提示词里出现它是正文，不是路径。这类假阳性最贵：它让判据变成噪音，
    然后没人再看它（本仓在 R114 的正文工具判据上已经栽过一次同款的坑）。

    口径因此收成两条**之一**：**带已知后缀**（`.md` / `.json` / …）**或结尾是 `/`**（目录）。
    `heuristic/inconclusive` 两条都不占 ⇒ 出局；而真的落点（`out/paper/main.tex`、
    `code/lean/`）两条各占其一 ⇒ 照判。
    """
    t = tok.rstrip("/")
    return tok.endswith("/") or t.lower().endswith(_PATH_SUFFIXES)


def _path_problems() -> list[str]:
    """正文/声明里点名的**带目录路径**，第一段必须在一张登记过的根表里。

    ## 为什么只查"带目录的"

    裸文件名（`main.pdf`、`dedup.py`）在这一批文本里都是**同句内已经给过全路径之后的简写**
    （"`out/paper/main.tex`（正文…）+ `main.pdf`"），或者是在点一个**模块名**
    （"归一化规则是盘上那一份（`dedup.py` 的 `normalize_doi`）"）。
    把裸名字也管起来只会制造假阳性，而假阳性让判据变成噪音 —— 所以这一格只查带目录的：
    那种写法**只有**两种可能，要么指个工作区里的真落点，要么指个仓库里的真文件，
    而两者都在登记表里。

    ## 三态

    这条判据不吃任何运行期输入（它查的是**文本里的字面**），所以只有"报"与"不报"两种结局；
    真正的三态在别处（读表能不能读成）。
    """
    out: list[str] = []
    roots = tuple(PATH_ROOTS)
    for owner, rows in CATALOG.items():
        for s in rows:
            for tok in sorted(set(_PATHY.findall(s.body))):
                if not _looks_like_a_path(tok) or tok.startswith(roots):
                    continue
                out.append(
                    f"{owner}/{s.slug}：正文里的路径 `{tok}` 不在登记过的根下"
                    f"（认 {'、'.join(roots)}）—— 没人往那儿写东西，读的人会扑空；"
                    "真要新增落点，请同时写进 `WORKSPACE_PATH_ROOTS`")
    for role, spec in sorted(builtin_specs_for_paths().items()):
        brief = spec.brief
        for label, text in (("policy", "\n".join(brief.policy)),
                            ("boundary", "\n".join(brief.boundary)),
                            ("deliverable", str(brief.deliverable)),
                            ("stance", "\n".join(brief.stance))):
            for tok in sorted(set(_PATHY.findall(text))):
                if not _looks_like_a_path(tok) or tok.startswith(roots):
                    continue
                out.append(
                    f"{role}.{label}：路径 `{tok}` 不在登记过的根下"
                    f"（认 {'、'.join(roots)}）—— 提示词里指一个没人写的落点，"
                    "角色会照它去扑空")
    return out


def builtin_specs_for_paths() -> dict[str, Any]:
    """十岗的声明（惰性取，`agent_skills` 不在导入期拖 `specs` 那条链）。"""
    from . import specs as _SP

    return dict(_SP.builtin_specs())


def _slug_problems() -> list[str]:
    """slug 那一格：非空、无空白、能当文件名、全目录唯一。

    ## 为什么值得单独查

    真机里出现过一条 slug 是 `" pessimistic-先找边界与反例"` —— **行首多了一个空格**。
    它不会让任何一格判据变红：`summary` / `when` / `body` 都齐，动作与工具都对，
    正文也确实能落盘。代价在两个看不见的地方：

    1. 盘上会多出一个 `skills/H/ pessimistic-先找边界与反例.md`（名字里有空格的**首字符**），
       而 `index_block` 印出来的路径与它逐字一致 —— 模型照抄那个路径 `fs.read` 是能读到的，
       于是一切"照常工作"，直到有人在别的工具里按名字对不上；
    2. 索引里两条 skill 的空格差异**人眼几乎看不见**，而机器一读就分得开。

    所以这一格必须是机器查的：**"读起来一样"不等于"是同一个名字"**。
    """
    out: list[str] = []
    seen: dict[str, str] = {}
    for owner, rows in CATALOG.items():
        for s in rows:
            slug = s.slug
            if not slug:
                out.append(f"{owner}：有一条 skill 的 slug 是空的")
                continue
            if slug != slug.strip():
                out.append(f"{owner}/{slug!r}：slug 首尾有空白（当文件名会带进去）")
            if any(ch.isspace() for ch in slug):
                out.append(f"{owner}/{slug!r}：slug 里不许有空白")
            if any(ch in slug for ch in '\\/:*?"<>|'):
                out.append(f"{owner}/{slug!r}：slug 里有不能当文件名的字符")
            if slug in seen:
                out.append(f"{owner}/{slug!r}：slug 与 {seen[slug]} 重了（索引里两条分不开）")
            else:
                seen[slug] = owner
    return out


def _role_tool_surface(problems: list[str]) -> dict[str, set[str]]:
    """每个角色**自己那一份**工具面（`角色 → 真名集合`）。

    ## 为什么不查"全注册表里有没有这个名字"

    第一版就是那样写的，而它当场把自己写坏的那四个工具名放过去了 ——
    错在两个地方，两处都是"查了个假面"：

    1. **`build_registry()` 不带 `workspace_root` 时 `fs.*` 整组不注册**
       （`secretary.py` 记过同一件事：不带 `store` 出 68 件、`fs.read` 不在里面；
       带上出 81 件、在里面）。于是 `fs.read` 这种**真名**会被报成"不在工具面上"
       —— 假阳性，而假阳性会让人开始不信这份判据。
    2. **"注册表里存在"不等于"这个角色拿得到"**：`fs.write` 在注册表里，
       而 H 是只读角色，`for_role("H")` 里没有它。一条 skill 说"H 用 fs.write 落盘"
       就是一句做不到的指令 —— 这正是本模块三条硬约束里第 2 条要挡的东西。

    所以这里按角色算面：`for_role(role)` 是 `tools/base.py` 里那份**已经过只读过滤**
    的工具面（它的 docstring 记着"实测就发生过 `fs.write` 混进 H 的工具面"）。

    三态：装配不出来 ⇒ 记一条 `problems`（"没查成"，不是"没问题"），返回空表；
    调用方见空表就跳过工具那一格（动作那一格仍然照查）。
    """
    try:
        import tempfile

        from .tools import TOOL_ROLES, build_registry

        root = tempfile.mkdtemp(prefix="agentflow-skills-surface-")
        reg = build_registry(workspace_root=root).registry
        return {str(r): {s.name for s in reg.for_role(str(r))} for r in TOOL_ROLES}
    except Exception as exc:  # noqa: BLE001
        problems.append(f"读不到按角色的工具面（这一格没查成）：{type(exc).__name__}: {exc}")
        return {}
