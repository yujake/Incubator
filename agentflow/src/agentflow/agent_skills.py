def index_block(role: str) -> str:
    """前置提示词里那一段（只放索引：路径 + 一句话 + 何时读）。

    为什么这一段的形状是"表格 + 一句纪律"：前置提示词每多一行，每一次模型调用都要
    重新付一次；而正文一旦被塞进来，"按需读"就退化成"还是全塞"。
    """
    rows = skills_for(role)
    if not rows:
        return ""
    lines = [
        "**你这一岗的 skills（现做现读）**：下面每一行是一份**盘上**的操作手册 ——",
        f"先看「什么时候读它」，对上了再用 `fs.read` 读 `{SKILLS_DIR}/<角色>/<名字>.md` 的全文。",
        # 2026-10-14 真机读数（两次真跑 16 + 3 次模型调用）：索引在提示词里、
        # 但一次正文都没被读过 —— 模型凭提示词里的规则就把活干完了。
        # 加这一句不是"再叮嘱一遍"，而是把读它为什么划算说出来：
        # 提示词给的是口径（每一格都要成立），手册给的是这一档的具体步骤与反面形态。
        "**对上了就现在读**：手册里写着这一档的**具体步骤**与**反面形态**（提示词只给口径，"
        "不给这些）—— 凭印象做，正是这些手册要防的那一种错。",
        "**不要**把它们当前置知识背下来：这里只给索引，正文按需读。",
        "",
        "| 名字（相对工作区根的路径） | 一句话 | 什么时候读它 |",
        "|---|---|---|",
    ]
    for s in rows:
        owner = SHARED if s in CATALOG.get(SHARED, ()) else str(role)
        lines.append(f"| `{skill_path(owner, s.slug)}` | {s.summary} | {s.when} |")
    lines.append("")
    lines.append("读了之后按它做；做了什么要落台账（**没有台账的那一步等于没发生**）。")
    # 2026-10-24（业主口径：形式化要不要做由用户指定，指定之后由 B 逐条安排）：
    # 这一格此前是"形式化见 L：`formal.*` 只挂在 L 身上，别自己写 Lean 源码……它的入口
    # 只有两条"—— 那是一句"去哪找谁"的指路 + 一句禁令，而协作面里除 B 以外没有谁与 L 有边。
    # 现在按正向指引重写：只写"这件事的结论以什么为准、谁安排的、回执是什么形状"，
    # 不写"别自己写"也不写"找 L"（禁令归判据：工具面没有 formal.*，越权一律 forbidden_edge）。
    # B 那一格不补这一句：它的收件通道写在 `specs/b.py` 的政策里（唯一该写全的地方）。
    from . import leanscope as _LEANSCOPE

    if (_LEANSCOPE.lean_on() and role not in _LEANSCOPE.LEAN_ONLY_ROLES
            and role not in ("B", "E")):
        lines.append("**形式化以 V 的签与 B 的台账为准**：要不要做由**用户**指定；"
                     "指定之后每一条由 **B** 逐条安排（一条才做一条），回执"
                     "（`experiments` 的 proof 行 + 原始输出原文 + 三态结论）由 B 带回。")
    return "\n".join(lines)


def materialize(root: str | pathlib.Path) -> list[str]:
    """把目录里的每条 skill 写到 `<root>/skills/<角色>/<slug>.md`；返回新写或改写的路径。

    幂等：内容与盘上逐字节相同就不写（免得每次开跑都把工作区搅一遍）。

    业主 2026-10-22（「在Lean开关没开时隔绝L」）：由 Lean 开关决定存在性的角色，开关
    关着时一份都不落盘 —— 落在 `<工作区>/skills/<角色>/` 里的手册是用户看得见的东西，
    那里出现 `skills/L/…` 就等于"L 今天存在、只是没派活"。
    """
    from . import leanscope as _LEANSCOPE

    base = pathlib.Path(root)
    written: list[str] = []
    for owner, rows in CATALOG.items():
        if _LEANSCOPE.is_hidden(owner):
            continue
        for s in rows:
            path = base / SKILLS_DIR / owner / f"{s.slug}.md"
            text = _render(owner, s)
            # 2026-10-24：手册正文也要过 Lean 关档改写 —— 它是模型会 fs.read 的东西。
            if not _LEANSCOPE.lean_on():
                for _old, _new in NO_LEAN_SKILL_REPLACEMENTS:
                    text = text.replace(_old, _new)
            try:
                if path.is_file() and path.read_text(encoding="utf-8") == text:
                    continue
                path.parent.mkdir(parents=True, exist_ok=True)
                path.write_text(text, encoding="utf-8", newline="\n")
            except OSError:
                continue        # 工作区不可写：不打断这一趟（提示词里那份索引仍然有效）
            written.append(str(path))
    return written


def _render(owner: str, s: Skill) -> str:
    """一条 skill 落盘的正文（头部三行是给人/给机器核对的，正文是操作手册）。"""
    head = [f"# {s.title}", "", f"- 名字：`{s.slug}`", f"- 属于：`{owner}`",
            f"- 什么时候读它：{s.when}", f"- 一句话：{s.summary}"]
    if s.actions:
        head.append(f"- 会用到的动作（角色.动作）：{', '.join(s.actions)}")
    if s.tools:
        head.append(f"- 会用到的工具：{', '.join(s.tools)}")
    return "\n".join(head) + "\n\n" + s.body.strip() + "\n"


def validate() -> list[str]:
    """逐条查"这条 skill 用到的动作/工具真的存在、且从拥有它的角色出发够得到"。

    三态纪律：查不成的（工具注册表读不出来）也要报出来 —— 不许把它读成"没问题"。

    业主 2026-10-22（「在Lean开关没开时隔绝L」）：开关关着时由它决定存在性的角色
    （`leanscope` 那份名单）这一趟不存在 ⇒ 不对它的 skills 下结论。这不是"查过了没问题"：
    那一档下它本来就不该出现在任何面上，落盘也被跳过（见 `materialize`）。
    """
    from . import leanscope as _LEANSCOPE

    problems: list[str] = []
    try:
        from . import capabilities as C
    except Exception as exc:  # noqa: BLE001
        return [f"读不到 capabilities（这一格没查成，不是没问题）：{type(exc).__name__}: {exc}"]
    surface = _role_tool_surface(problems)
    problems.extend(_slug_problems())
    problems.extend(_body_action_problems())
    problems.extend(_path_problems())
    for owner, rows in CATALOG.items():
        if _LEANSCOPE.is_hidden(owner):
            continue
        for s in rows:
            if not s.summary.strip() or not s.when.strip() or not s.body.strip():
                problems.append(f"{owner}/{s.slug}：summary / when / body 三格都不许空")
            for item in s.actions:
                role, _, action = item.partition(".")
                if not role or not action:
                    problems.append(f"{owner}/{s.slug}：动作要写成 角色.动作，收到 {item!r}")
                    continue
                spec = C.find_action(role, action)
                if spec is None:
                    problems.append(f"{owner}/{s.slug}：{item} 不是本系统里存在的动作")
                    continue
                if owner == SHARED or role == owner:
                    continue
                if role not in set(C.ALLOWED_EDGES.get(owner, ())):
                    problems.append(
                        f"{owner}/{s.slug}：{item} 这个角色不在 {owner} 的出边里"
                        "（写进去就是一句做不到的指令）")
            for name in s.tools:
                if not surface:
                    continue
                for who in (sorted(surface) if owner == SHARED else [owner]):
                    if name not in surface.get(who, set()):
                        problems.append(f"{owner}/{s.slug}：工具 {name} 不在 {who} 的工具面上")
    problems.extend(_body_tool_problems(surface))
    problems.extend(_unknown_tool_problems(surface))
    return problems


#: 正文里那种"点名一件工具"的写法：反引号包着的 `组.名`（全小写组名）。
#:
#: 为什么要有这个正则而不是"看见像工具就报"：正文里还会出现 `D.propose_question`
#: （动作，角色名大写）、`data/statements.json`（路径）、`main.tex`（文件名）——
#: 它们都不是工具。只报"确实在工具面上存在、但不属于这个角色"的那一种，
#: 这样零假阳性，而真缺陷（"V 用 `fs.write` 落盘"这种做不到的指令）一个不漏。
_BODY_TOOL_TOKEN = re.compile(r"`([a-z][a-z0-9_]*\.[a-z0-9_]+)`")


def _body_tool_problems(surface: dict[str, set[str]]) -> list[str]:
    """正文里点名的工具也必须在这个角色自己的工具面上。

    ## 为什么 `tools` 那一格不够

    `tools` 是声明，正文是操作手册。一条 skill 完全可以把 `tools=("fs.read",)`
    写得干干净净，却在正文第一句写"用 `fs.write` 把结果落盘" —— 而 `fs.write`
    正是只读角色拿不到的那一件。声明那一格查得再严也管不到这句话，
    而模型照做的对象是正文。

    ## `shared` 那一槽为什么豁免（这是明写出来的豁免，不是漏查）

    `shared` 是每个角色都读得到的同一份文件。它此前声明用 `table.*`，
    而 M 的工具面里没有库表类工具 ⇒ 那两句对 M 是做不到的指令。改法不是"把它删干净"，
    而是在正文里点明这一格与角色有关（"库表工具在多数角色手上、主控用 `fs.read`
    读同一份 JSON"）—— 那句话里必然同时出现 `table.get` 与 `fs.read`，
    所以对共享那一份，按"每个角色都必须在面上"判会把它自己判死。
    共享那一份的纪律因此是声明那一格（`tools`）取交集，判据在 `validate()` 的工具循环里。
    """
    known: set[str] = set()
    for names in surface.values():
        known |= names
    if not known:
        return []          # 工具面没读成 ⇒ 这一格跳过（validate 已经记过"没查成"）
    out: list[str] = []
    for owner, rows in CATALOG.items():
        if owner == SHARED:
            continue
        allowed = surface.get(owner, set())
        for s in rows:
            for tok in sorted(set(_BODY_TOOL_TOKEN.findall(s.body))):
                if tok in known and tok not in allowed:
                    out.append(
                        f"{owner}/{s.slug}：正文里点名了工具 {tok}，但它不在 {owner} 的工具面上"
                        "（声明那一格查不出这种写法，而模型照做的是正文）")
    return out


def _unknown_tool_problems(surface: dict[str, set[str]]) -> list[str]:
    """正文里点名的"组名对得上、名字却不存在"的那种工具 —— 补 `_body_tool_problems` 的漏。

    ## 那一条漏在哪
    它的判据是「这个名字存在，但不在你这个角色的面上」（`tok in known`）。一个根本
    不存在的名字在那边静默放过：`conductor.stats` 的真身是
    `conductor.ledger(view="stats")`，全仓没有前一件工具，于是模型照着它调只会拿到
    `unknown_action`，而手册与 validate 都一声不吭（2026-10-26 实测）。

    ## 为什么按「工具组」收窄
    正文里还有 `data/statements.json`（路径）、`main.tex`（文件名）、
    `documents.claims`（台账字段）、`experiments.search_bound`（台账字段）、
    `policy.check`（模块函数）—— 它们的组名都不是工具组。组名取自当前工具面里真实
    出现的那些前缀，所以这里零假阳性：报出来的每一条都是"该用哪一件记错了"。
    """
    from . import leanscope as _LEANSCOPE

    known: set[str] = set()
    for names in surface.values():
        known |= names
    if not known:
        return []          # 工具面没读成 ⇒ 这一格跳过（validate 已经记过"没查成"）
    groups = {name.split(".")[0] for name in known}
    out: list[str] = []
    for owner, rows in CATALOG.items():
        if owner == SHARED or _LEANSCOPE.is_hidden(owner):
            continue
        for s in rows:
            for tok in sorted(set(_BODY_TOOL_TOKEN.findall(s.body))):
                if tok in known:
                    continue    # 存在：属于别的角色由 `_body_tool_problems` 报
                if tok.split(".")[0] in groups:
                    out.append(
                        f"{owner}/{s.slug}：正文里点名了工具 {tok}，而工具面上没有这个名字"
                        "（像是把『该用哪一件』记错了：先查面再写）")
    return out


#: 正文里那种"点名一个动作"的写法：反引号包着的 `大写角色.动作`。
#: 形状与工具名天然分得开（工具是全小写的 `组.名`），所以这个正则零假阳性：
#: `data/statements.json`（路径）、`main.tex`（文件名）、`re.compile`（标准库）
#: 都不会命中。零假阳性是这条判据能活下来的前提。
_BODY_ACTION_TOKEN = re.compile(r"`([A-Z])\.([a-z][a-z0-9_]*)`")

#: 正文里指到别人的那种 `角色.动作`（不是让本角色去做）：逐条登记 + 一行理由。
#:
#: ## 口径
#:
#: 正文里的 `角色.动作` 默认必须从拥有这条 skill 的角色出发够得到（与 `actions`
#: 那一格同一条纪律）。登记在这里的是例外 —— 它们出现在"这不是我的活"的句子里，
#: 指到别人或别人产出的证据。逐条登记而不是放宽判据：多出一处就要有人看一眼
#: "这是指到别人，还是真让人去做"。
#:
#: ## 反例比正例重要（为什么不干脆只查"动作存不存在"）
#:
#: 只查存在性会漏掉真缺陷：一条 skill 说"你自己去调 `F.step`"时，动作确实存在，
#: 而那个角色做不到。而如果为了抓这一句就把"指到别人"也判红，判据立刻变成噪音
#: （实测这三处都是正当的指到别人）——所以豁免必须具名，且必须能被反查（见下）。
_BODY_CROSS_REFS: dict[tuple[str, str, str], str] = {
    # 2026-10-20 业主裁定：改回 C 无出边、由 D 唤起 C ⇒ 这条豁免按原句恢复
    # （2026-10-20 那一批曾因 `ALLOWED_EDGES["C"] = {"D"}` 把它删掉：那时 C 够得到 D）。
    # 现在 C 又够不到 D 了 ⇒ 那句"矛盾问题的闭环由 D 的 `D.adjudicate` 收口"重新是
    # "指到别人"，不登记就会被 `_body_action_problems` 第 3 件事当场报出来。
    ("C", "矛盾-三态并指到那一对", "D.adjudicate"):
        "「C 只判、不改：矛盾问题的闭环由 D 的 `D.adjudicate` 收口（I2）」—— 指到别人",
    ("G", "成稿-正文自己写", "H.review"):
        "「稿件级审校由 **H** 做（`H.review`）」—— 指到别人",
    # 2026-10-22 第四批：这句里的动作从 `E.check_formal` 改成 `L.check_formal`
    # （形式化那一岗从 E 划到 L），登记跟着换键 —— 换键之后它仍然"够不到"（V 没有到 L 的边），
    # 所以它仍然是"指到别人"那一档，不是该删的腐烂条目。
    ("V", "假设轴-前提是否真被满足", "L.check_formal"):
        "「能机器核的（`L.check_formal` 过的那几条）」—— 指到别人（形式化那一岗）产出的证据",
}


def _body_action_problems() -> list[str]:
    """正文里提到的动作：必须真存在；够不到就要具名登记为"指到别人"。

    `actions` 那一格是声明，正文是操作手册 —— 一句"派 `F.step` 去推"写在正文里，
    声明那一格查得再严也管不到它，而模型照做的对象是正文（与
    `_body_tool_problems` 同一条理由，只是这一格查的是动作而不是工具）。

    三件事各查一遍：

    1. 存在：正文里任何一个 `角色.动作` 都必须在 `capabilities` 里（业主 ④：
       严禁虚构本系统不存在的动作）；
    2. 够得到：从拥有这条 skill 的角色出发，要么是自己的动作、要么在它的出边里；
       够不到但确实是"指到别人"的，必须登记进 `_BODY_CROSS_REFS`；
    3. 登记不许腐烂：登记过的每一条都必须还成立（skill 还在、正文里还有那一句、
       而且从出边看仍然够不到）—— 一张永不生效的豁免表会腐烂成"看起来还在挡着什么"。
    """
    try:
        from . import capabilities as C
    except Exception as exc:  # noqa: BLE001 —— 没查成也要报（不许读成"没问题"）
        return [f"读不到 capabilities（正文动作那一格没查成）：{type(exc).__name__}: {exc}"]
    out: list[str] = []
    hit: set[tuple[str, str, str]] = set()
    for owner, rows in CATALOG.items():
        for s in rows:
            reachable = set(C.ALLOWED_EDGES.get(owner, ()))
            for role, action in sorted(set(_BODY_ACTION_TOKEN.findall(s.body))):
                item = f"{role}.{action}"
                if C.find_action(role, action) is None:
                    out.append(f"{owner}/{s.slug}：正文里的 {item} 不是本系统里存在的动作")
                    continue
                if owner == SHARED or role == owner or role in reachable:
                    continue
                key = (owner, s.slug, item)
                if key in _BODY_CROSS_REFS:
                    hit.add(key)
                    continue
                out.append(
                    f"{owner}/{s.slug}：正文里的 {item} 不在 {owner} 的出边里"
                    "（写进去就是一句做不到的指令）。若这一句是「指到别人」，"
                    "请登记进 `_BODY_CROSS_REFS` 并写明理由")
    for key, why in sorted(_BODY_CROSS_REFS.items()):
        if key not in hit:
            out.append(
                f"{key[0]}/{key[1]}：`_BODY_CROSS_REFS` 里登记的 {key[2]} 已经不成立"
                f"（要么这句正文没了、要么它现在够得到了）⇒ 请删掉这条登记，"
                f"别让豁免表腐烂。理由原话：{why}")
    return out


