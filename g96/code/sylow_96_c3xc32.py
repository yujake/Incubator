#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""
sylow_96_c3xc32.py -- explicit witness for the cell (n_3, n_2) = (1, 1)
of groups of order 96 = 2^5 * 3.

G = C_3 x C_32, elements (a, b) with a in Z/3, b in Z/32, group law
componentwise addition mod 3 and mod 32.  Pure Python 3.  No network,
no GAP, no randomness, no external data.  Every number printed here or
put into REPRO_RESULT is computed from the 96 elements by this script.

What this script is for
-----------------------
experiments/000000 (code/sylow_96.py) enumerated the counting constraints
for the six cells (n_3, n_2), but the *claim string* attached to that run
contained the extra sentence

    "由此排除 n_2=1 的四格（n_2=1 => 2-元集合大小 = 32 != 96-2n_3）"

That sentence is FALSE and this script refutes it with a concrete group:
in G = C_3 x C_32 we have n_3 = 1, n_2 = 1 (so n_2 = 1 is *not* excluded),
2-elements = 32, elements of order 3 = 2, and 96 - 2*1 = 94 elements are
not of order 3.  Those 94 split as 32 two-elements + 62 elements whose
order is divisible by 3 but > 3 (orders 6, 12, 24, 48, 96).  So "2-elements
= 96 - 2*n_3" does not follow from trivial intersection of the Sylow
3-subgroups: it additionally needs "no element of order 3*2^k", which is
not implied.

The CSV reading (out/sylow_96.csv, row "n3=1,n2=1": leftover 94,
two_elements_min = two_elements_max = 32, order3div_gt3 = [62,62],
counting_feasible = True) is confirmed element by element here.

Repro:  python code/sylow_96_c3xc32.py
"""
import json
import sys
import time

T0 = time.time()
ORDER = 96
checks = []


def chk(name, ok, detail=""):
    checks.append({"check": name, "ok": bool(ok), "detail": detail})
    print("CHECK %-46s %-4s %s" % (name, "OK" if ok else "FAIL", detail))


# ------------------------------------------------------------------ group
ELS = [(a, b) for a in range(3) for b in range(32)]
IDENT = (0, 0)


def mul(x, y):
    return ((x[0] + y[0]) % 3, (x[1] + y[1]) % 32)


def inv(x):
    return ((-x[0]) % 3, (-x[1]) % 32)


def order(x):
    # 修正：旧版先自乘再判，返回值恒为真阶 - 1（阶谱键因此全线差一）
    r, k = x, 1
    while r != IDENT:
        r = mul(r, x)
        k += 1
    return k


chk("|G| = 96", len(ELS) == ORDER, "|G| = %d" % len(ELS))

ORD = {e: order(e) for e in ELS}
SPECTRUM = {}
for e in ELS:
    SPECTRUM[ORD[e]] = SPECTRUM.get(ORD[e], 0) + 1
print("order spectrum of C_3 x C_32: %s" % dict(sorted(SPECTRUM.items())))

# theory: for (a,b), ord = lcm(ord_3(a), ord_32(b))
EXPECTED = {1: 1, 2: 1, 3: 2, 4: 2, 6: 2, 8: 4, 12: 4,
            16: 8, 24: 8, 32: 16, 48: 16, 96: 32}
chk("order spectrum matches lcm formula", SPECTRUM == EXPECTED,
    "spectrum=%s" % dict(sorted(SPECTRUM.items())))
chk("spectrum sums to |G|", sum(SPECTRUM.values()) == ORDER,
    "sum=%d" % sum(SPECTRUM.values()))
chk("group is abelian (all pairs commute)",
    all(mul(x, y) == mul(y, x) for x in ELS for y in ELS), "96^2 = 9216 pairs")

# two-elements: order is a power of 2 ; three-elements: order divides 3
TWO = set(e for e in ELS if ORD[e] & (ORD[e] - 1) == 0)
THREE = set(e for e in ELS if 3 % ORD[e] == 0)


def is_subgroup(S):
    if IDENT not in S:
        return False
    for x in S:
        for y in S:
            if mul(x, y) not in S:
                return False
    return True


chk("2-elements form a subgroup of order 32",
    is_subgroup(TWO) and len(TWO) == 32, "|{g : ord(g) is a 2-power}| = %d" % len(TWO))
chk("3-elements form a subgroup of order 3",
    is_subgroup(THREE) and len(THREE) == 3, "|{g : ord(g) | 3}| = %d" % len(THREE))

# n_3 counted exactly: distinct cyclic subgroups generated by elements of order 3
SUBS3 = set()
for g in ELS:
    if ORD[g] == 3:
        SUBS3.add(frozenset({IDENT, g, mul(g, g)}))
N3 = len(SUBS3)
# n_2: the union of all Sylow 2-subgroups is exactly the set of 2-elements;
# if that set is itself a subgroup of order 32 it is the unique Sylow 2-subgroup.
N2 = 1 if (is_subgroup(TWO) and len(TWO) == 32) else None
chk("n_3 = 1", N3 == 1, "distinct subgroups of order 3: %d" % N3)
chk("n_2 = 1 (unique Sylow 2)", N2 == 1,
    "2-element set is a subgroup of order %d, hence the only Sylow 2" % len(TWO))


def normalizer(S):
    return set(g for g in ELS if set(mul(mul(inv(g), s), g) for s in S) == set(S))


NGQ = normalizer(THREE)
NGP = normalizer(TWO)
chk("|N_G(Q)| = 96/n_3", len(NGQ) * N3 == ORDER,
    "|N_G(Q)| = %d, [G:N_G(Q)] = %d = n_3" % (len(NGQ), ORDER // len(NGQ)))
chk("|N_G(P)| = 96/n_2", len(NGP) * N2 == ORDER,
    "|N_G(P)| = %d, [G:N_G(P)] = %d = n_2" % (len(NGP), ORDER // len(NGP)))

# ------------------------------------------------- the refuted quantity
ORDER3_COUNT = SPECTRUM.get(3, 0)
LEFT = ORDER - ORDER3_COUNT
TWO_COUNT = len(TWO)
THREE_DIV_GT3 = sum(1 for e in ELS if ORD[e] % 3 == 0 and ORD[e] > 3)
print("elements of order 3            = %d  (= 2*n_3 = %d)" % (ORDER3_COUNT, 2 * N3))
print("elements NOT of order 3        = %d  (= 96 - 2*n_3 = %d)" % (LEFT, ORDER - 2 * N3))
print("  of which 2-elements          = %d" % TWO_COUNT)
print("  of which ord divisible by 3 but > 3 = %d  (orders 6,12,24,48,96)" % THREE_DIV_GT3)
chk("leftover decomposes", TWO_COUNT + THREE_DIV_GT3 == LEFT,
    "%d + %d = %d" % (TWO_COUNT, THREE_DIV_GT3, LEFT))
chk("2-elements != leftover (so '2-elements = 96-2n_3' fails here)",
    TWO_COUNT != LEFT, "%d != %d" % (TWO_COUNT, LEFT))
for k in (6, 12, 24, 48, 96):
    print("PROGRESS: " + json.dumps({"order": k, "count": SPECTRUM.get(k, 0)},
                                  sort_keys=True))

COUNTEREXAMPLE = {
    "group": "C_3 x C_32 (direct product, componentwise addition)",
    "group_order": ORDER,
    "n_3": N3,
    "n_2": N2,
    "NGQ": len(NGQ),
    "NGP": len(NGP),
    "num_elements_order_3": ORDER3_COUNT,
    "num_2_elements": TWO_COUNT,
    "num_order_divisible_by_3_gt_3": THREE_DIV_GT3,
    "leftover_not_order3": LEFT,
    "trivial_sylow3_intersection": True,
    "note": ("n_3 = 1 makes 'distinct Sylow 3-subgroups intersect trivially' "
             "vacuously true, yet n_2 = 1 occurs here: so that hypothesis "
             "does not force n_2 = 3, and the 2-element count is 32, not "
             "96 - 2*n_3 = 94."),
}

REFUTED = ("在 |G| = 96 且「不同 Sylow 3-子群交于单位元」成立时，"
           "n_2 = 1 的格子被排除：因为 2-元个数 = 96 - 2*n_3，"
           "与 32 不符（n_2 = 1 迫使 2-元个数 = 32）")

ok_all = all(c["ok"] for c in checks)
print("checks: %d/%d passed" % (sum(1 for c in checks if c["ok"]), len(checks)))
summary = {
    "result": "refutes" if ok_all else "inconclusive",
    "refuted_statement": REFUTED,
    "counterexample": COUNTEREXAMPLE if ok_all else None,
    "group_order": ORDER,
    "order3_count_iff_trivial_intersection": ORDER3_COUNT,
    "leftover_not_order3": LEFT,
    "two_elements": TWO_COUNT,
    "order_divisible_by_3_gt_3": THREE_DIV_GT3,
    "identity_ok": all(c["ok"] for c in checks),
    "checks_passed": sum(1 for c in checks if c["ok"]),
    "checks_total": len(checks),
    "bound": ("complete enumeration of the 96 elements of the single explicit "
              "group C_3 x C_32; no search over groups"),
    "strategy": ("explicit construction + brute force over 96 elements "
                 "(order spectrum, subgroup closure, normaliser closure)"),
    "scaling": {"elements": ORDER, "pairs_commuted": ORDER * ORDER,
                "seconds": round(time.time() - T0, 4)},
    "unverified": [
        "number of isomorphism classes of groups of order 32 (51 NOT verified here)",
        "number of isomorphism classes of groups of order 96 (231 NOT verified here)",
        "which of the six cells (n_3,n_2) are realised by some group of order 96",
    ],
}
print("REPRO_RESULT: " + json.dumps(summary, ensure_ascii=False, sort_keys=True))
if not ok_all:
    for c in checks:
        if not c["ok"]:
            print("FAILED CHECK: %s :: %s" % (c["check"], c["detail"]))
    sys.exit(1)
sys.exit(0)
